const normRefText=x=>{const d=NORM_DOCS[x.doc];return x.ref?d.full+(d.sep||', ')+x.ref:d.full};
// Ссылки правила с учётом выбранного источника: 'both' | 'PR91' | 'G72509'
function ruleRefs(rule,source='both'){
 const main=rule.refs.filter(x=>x.doc==='PR91'||x.doc==='G72509');
 let keep=main;
 if(source!=='both'){const pref=main.filter(x=>x.doc===source);if(pref.length)keep=pref}
 return [...keep,...rule.refs.filter(x=>!main.includes(x))];
}
