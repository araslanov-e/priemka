/* ---------- Подбор ---------- */
const normText=s=>' '+String(s||'').toLowerCase().replace(/ё/g,'е').split(/[^a-zа-я0-9]+/).filter(Boolean).join(' ')+' ';
function kwHit(t,kw){if(kw[0]==='=')return t.includes(' '+kw.slice(1)+' ');return t.includes(' '+kw)}
const anyHit=(t,list)=>list.some(k=>kwHit(t,k));
// Возвращает подходящие правила, лучшие сверху. category — название конструктива (учитывается как контекст).
function matchNorms(text,category){
 const tText=normText(text),tAll=normText(text+' '+(category||''));
 if(tText.trim()==='')return [];
 const out=[];
 NORM_RULES.forEach((r,i)=>{
  if(r.not&&anyHit(tAll,r.not))return;
  if(r.notText&&anyHit(tText,r.notText))return;
  if(!r.match.every(g=>anyHit(tAll,g)))return;
  const fromText=r.match.filter(g=>anyHit(tText,g)).length;
  if(!fromText)return; // одного контекста мало — хотя бы одно слово должно быть в описании
  out.push({rule:r,score:r.match.length*10+fromText*5-i*0.01});
 });
 return out.sort((a,b)=>b.score-a.score).map(x=>x.rule);
}
